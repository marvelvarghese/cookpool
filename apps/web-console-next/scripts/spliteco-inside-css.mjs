// Writes src/styles/spliteco-inside.css from Spliteco's stylesheet, scoped
// under `.spx` (money-inside MN-8). Run after Spliteco's globals.css changes;
// a test fails while the two differ.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { scopeCss } from "../src/lib/scope-css.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "../../spliteco-web/src/app/globals.css"), "utf8");
const header = "/* Generated by scripts/spliteco-inside-css.mjs from apps/spliteco-web/src/app/globals.css. Do not edit. */\n";
writeFileSync(join(here, "../src/styles/spliteco-inside.css"), header + scopeCss(src) + "\n");
